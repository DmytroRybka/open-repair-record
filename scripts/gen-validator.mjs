// Precompiles the JSON Schema into plain JavaScript, so the browser never compiles code at runtime ("new Function").
// That keeps the editor working under a strict Content-Security-Policy without 'unsafe-eval' (the self-hosted
// image sends one). Run after changing the schema:  npm run gen:validator   (a unit test fails if you forget).
import { readFileSync, writeFileSync } from "node:fs";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

export const TARGET = new URL("../src/lib/orr-validator.generated.js", import.meta.url);

export function generate() {
  const schema = JSON.parse(readFileSync(new URL("../src/schema/orr-1.0.schema.json", import.meta.url), "utf8"));
  const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } });
  const code = standaloneCode(ajv, ajv.compile(schema));
  return "// Generated by scripts/gen-validator.mjs from src/schema/orr-1.0.schema.json. Do not edit.\n// @ts-nocheck\n" + code + "\n";
}

if (process.argv[1]?.endsWith("gen-validator.mjs")) {
  writeFileSync(TARGET, generate());
  console.log("src/lib/orr-validator.generated.js written");
}
